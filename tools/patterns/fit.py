"""Подбирает кадр каждого паттерна под оригинал из брендбука.

Для каждого поворота и масштаба лучший сдвиг находится взаимной корреляцией
через БПФ, затем результат уточняется подъёмом по совпадению линий.
Узор самоподобен — копии знака похожи друг на друга, — поэтому случайный
поиск здесь путается, а корреляция нет.

Запуск из этой папки (нужны numpy и Pillow):
    python fit.py            — все семь
    python fit.py 4 5 6      — выбранные
Результат в fit.json, значения переносятся в PATTERN_VARIANTS в app.js.

Кадр 4 подборщик уводит в ложный ответ из двух прямых. На глаз это тот же
ракурс, что 5 и 6, поэтому его считают локально от кадра 6
(поворот около -130, масштаб около 2).
"""
import sys, json, time, numpy as np
from fitlib import fit, rec

ids = [int(x) for x in sys.argv[1:]] or range(1, 8)
out = {}
for i in ids:
    t = time.time()
    s, p = fit(i, np.arange(-180, 180, 5), np.geomspace(0.8, 6.0, 16))
    out[i] = rec(s, p)
    print(i, out[i], f'{time.time() - t:.0f} с', flush=True)
json.dump(out, open('fit.json', 'w'), indent=1)
