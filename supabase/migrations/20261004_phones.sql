Проблема в другом: сейчас они разложены вразнобой. На сайте +7 (922) 301-88-80, в описании Telegram-канала +7 (995) 926-54-20, и в поисковой выдаче как контакт ADERVIS показывается именно второй. Человек видит один номер в одном месте, другой в другом и не понимает, куда звонить — а если попал на тот, что заведён под привязки, может не дождаться ответа.

