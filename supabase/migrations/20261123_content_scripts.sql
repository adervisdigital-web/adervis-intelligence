-- только с датой. Отдельная таблица не нужна: это та же публикация со
-- статусом «Сценарий», приложение показывает её в своём разделе.

alter table public.content drop constraint if exists content_status_check;
alter table public.content add constraint content_status_check
  check (status in ('Сценарий', 'Идея', 'Черновик', 'На проверке', 'Утверждено', 'Опубликовано'));
